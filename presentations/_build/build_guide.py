LTR_RUN = re.compile(r"[A-Za-z0-9\[\(+−\-±&γβα√][A-Za-z0-9 _+−\-±.,:/=×%&\[\]\(\)'^γβαΣ·|<>√≈→∝÷²…]*[A-Za-z0-9\]\)%γβα²]"
                     r"|[A-Za-z0-9]")


def T(raw):
    """Escape, isolate Latin/number runs (so RTL never flips them), `code`, **bold**."""
    out = []
    for i, part in enumerate(re.split(r"`([^`]+)`", raw)):
        if i % 2:
            out.append(f'<code dir="ltr">{html.escape(part)}</code>')
            continue
        pos = 0
        for m in LTR_RUN.finditer(part):
            a, b = m.start(), m.end()
            while a < b and part[a] in "([" and part[a:b].count(part[a]) > part[a:b].count(")]"["([".index(part[a])]):
                a += 1                                   # "(Contact" -> the bracket stays RTL and mirrors correctly
            while b > a and part[b - 1] in ")]" and part[a:b].count(part[b - 1]) > part[a:b].count("(["[")]".index(part[b - 1])]):
                b -= 1
            if a == b:
                continue
            out.append(html.escape(part[pos:a]))
            nw = " nw" if " " not in part[a:b] else ""           # keep "Apache-2.0" or "2e-5" on one line
            out.append(f'<span class="ltr{nw}" dir="ltr">{html.escape(part[a:b])}</span>')
            pos = b
        out.append(html.escape(part[pos:]))
    s = "".join(out)
    return re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)


H = []                                    # the document body
def add(x): H.append(x)
def H1(t, brk=False): add(f'<h1 class="{"brk" if brk else ""}">{T(t)}</h1>')
def H2(t): add(f"<h2>{T(t)}</h2>")
def H3(t): add(f"<h3>{T(t)}</h3>")
def P(t): add(f"<p>{T(t)}</p>")
def UL(items): add("<ul>" + "".join(f"<li>{T(i)}</li>" for i in items) + "</ul>")
def OL(items): add("<ol>" + "".join(f"<li>{T(i)}</li>" for i in items) + "</ol>")
def CODE(t): add(f'<pre dir="ltr">{html.escape(t)}</pre>')


def BOX(kind, title, body):
    """kind: say (ready sentence), trap (careful), key (remember), info."""
    inner = "".join(f"<p>{T(b)}</p>" if isinstance(b, str) else
                    "<ul>" + "".join(f"<li>{T(i)}</li>" for i in b) + "</ul>" for b in body)
    add(f'<div class="box {kind}"><div class="boxtitle">{T(title)}</div>{inner}</div>')


def TABLE(header, rows, widths=None, cls=""):
    cols = "".join(f'<col style="width:{w}%">' for w in widths) if widths else ""
    head = "".join(f"<th>{T(h)}</th>" for h in header)
    body = ""
    for r in rows:
        hi = isinstance(r, tuple) and len(r) == 2 and r[0] == "HI"
        cells = r[1] if hi else r
        body += f'<tr class="{"hi" if hi else ""}">' + "".join(f"<td>{T(str(c))}</td>" for c in cells) + "</tr>"
    add(f'<table class="{cls}"><colgroup>{cols}</colgroup><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>')


def QA(q, a):
    a_html = "".join(f"<p>{T(x)}</p>" for x in (a if isinstance(a, list) else [a]))
    add(f'<div class="qa"><div class="q">{T(q)}</div><div class="a">{a_html}</div></div>')


def FIG(path, caption, width=100):
    add(f'<figure><img src="{path.resolve().as_uri()}" style="width:{width}%"><figcaption>{T(caption)}</figcaption></figure>')


